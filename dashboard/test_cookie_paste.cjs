const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync(__dirname+'/static/app.js','utf8');
const elements={cookieLength:{},cookieError:{},cookieValue:{value:'SESSDATA=OLD_TEST',setAttribute(){}},cookieForm:{}};
for(const element of Object.values(elements))element.addEventListener=function(event,handler){this[event]=handler};
const context=vm.createContext({$:id=>elements[id]});
vm.runInContext(source.slice(source.indexOf('function cookieError('),source.indexOf("$('settingsForm').addEventListener")),context);
assert.equal(vm.runInContext("cookiePasteValue('Cookie: SESSDATA=TEST%2CSESSION==; x=1')",context),'SESSDATA=TEST%2CSESSION==; x=1');
assert.equal(vm.runInContext("cookiePasteValue('GET / HTTP/1.1\\r\\nCookie: SESSDATA=TEST\\r\\nAccept: */*')",context),'SESSDATA=TEST');
assert.throws(()=>vm.runInContext("cookiePasteValue('Cookie: SESSDATA=TEST\\nCookie: x=1')",context),/多个/);
assert.throws(()=>vm.runInContext("cookiePasteValue('SESSDATA=TEST\\nx=1')",context),/多行/);
assert.throws(()=>vm.runInContext("cookiePasteValue('Cookie: SESSDATA=TEST\\n remaining')",context),/换行拆开/);
let prevented=false;
elements.cookieValue.paste({clipboardData:{getData:()=> 'Cookie: SESSDATA=NEW_TEST\nCookie: SESSDATA=OTHER_TEST'},preventDefault(){prevented=true}});
assert.equal(prevented,true);
assert.equal(elements.cookieValue.value,'');
assert.match(elements.cookieError.textContent,/多个/);
assert.equal(elements.cookieError.hidden,false);
assert.equal(elements.cookieLength.textContent,'0 个字符');
const full='SESSDATA='+('ABC123%2C'.repeat(1600))+'; other=value';
elements.cookieValue.value=full;
elements.cookieValue.input();
assert.equal(elements.cookieValue.value,full);
assert.equal(elements.cookieLength.textContent,full.length.toLocaleString('zh-CN')+' 个字符');
elements.cookieValue.paste({clipboardData:{getData:()=> 'Cookie: '+full},preventDefault(){}});
assert.equal(elements.cookieValue.value,full);
assert.equal(elements.cookieLength.textContent,full.length.toLocaleString('zh-CN')+' 个字符');
elements.cookieValue.value='';
vm.runInContext('updateCookieLength()',context);
assert.equal(elements.cookieLength.textContent,'0 个字符');
const html=fs.readFileSync(__dirname+'/static/index.html','utf8');
assert.match(html,/<textarea[^>]*id="cookieValue"[^>]*wrap="soft"[^>]*>/);
assert.doesNotMatch(html,/<(?:input|textarea)[^>]*id="cookieValue"[^>]*(?:type="password"|maxlength=)/);
console.log('Cookie paste and visible editor tests passed; long values remain complete.');
